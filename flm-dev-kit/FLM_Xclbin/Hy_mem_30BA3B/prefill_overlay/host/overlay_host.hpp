// must match iron/layout.py
constexpr uint32_t RTP_ADDR = 61696;    // every core's RTP block (checked in the build)
constexpr int RTP_OP = 0, RTP_CALLS = 1, RTP_SWITCHED = 2;
constexpr int RTP_DQ_K_DIV_K = 4, RTP_DQ_ACT = 5;
constexpr int RTP_AT_L_BEGIN = 8, RTP_AT_L_CHUNKS = 9, RTP_AT_WINDOW = 10;
constexpr int OP_DQ = 1, OP_ATTN = 2;
constexpr uint32_t OP_LOCK_REG = 0x1F000 + 16 * 15;   // core lock 15 value register
constexpr uint32_t DMA_CTRL_RESET = 0x2;              // bit 1 of a DMA channel control register
constexpr int ROWS = 4, COLS = 8, ATTN_COLS = 4;

inline void write_reg(npu_sequence* seq, uint32_t row, uint32_t col, uint32_t offset, uint32_t value) {
    seq->rtp_write(get_tile(row, col), offset, value);
}

inline const op_config& config_of(int op) {
    return op == OP_DQ ? op_dq : op_attn;
}

using reg_key = std::tuple<uint32_t, uint32_t, uint32_t>;

/// @brief (col, row, offset) of every register of one kind that either op writes
template <typename Get>
inline std::vector<reg_key> union_of(Get get) {
    std::set<reg_key> all;
    for (const op_config* cfg : {&op_dq, &op_attn})
        for (const reg_write& w : get(*cfg)) all.insert({w.col, w.row, w.offset});
    return {all.begin(), all.end()};
}

/// @brief the value `regs` gives (col, row, offset), 0 if it doesn't write it
inline uint32_t value_in(const std::vector<reg_write>& regs, const reg_key& key) {
    for (const reg_write& w : regs)
        if (w.col == std::get<0>(key) && w.row == std::get<1>(key) && w.offset == std::get<2>(key)) return w.value;
    return 0;
}

inline size_t write_bd(npu_sequence* seq, const reg_block& b) {
    for (size_t i = 0; i < b.words.size(); i++) write_reg(seq, b.row, b.col, b.offset + 4 * (uint32_t)i, b.words[i]);
    return b.words.size();
}

/// @brief configure the array for op `to`: stop the DMA channels, then write
///        the op's stream switches, BDs and lock values, then start its chains.
/// @param from the op configured now; -1 = unknown (fresh load, or another
///        xclbin ran since), which means a full write of everything
/// @return number of register writes
inline size_t gen_switch(npu_sequence* seq, int to, int from) {
    static const std::vector<reg_key> sw_regs = union_of([](const op_config& c) -> const auto& { return c.sw; });
    static const std::vector<reg_key> lock_regs = union_of([](const op_config& c) -> const auto& { return c.locks; });
    const op_config& cfg = config_of(to);
    const bool full = from != OP_DQ && from != OP_ATTN;
    size_t writes = 0;

    // 1. reset the channels the old op runs on: its chains loop forever,
    //    waiting on a lock (the other op's channels are idle already)
    auto reset = [&](uint32_t row, uint32_t col, uint32_t offset) {
        seq->npu_maskwrite(get_tile(row, col), offset, DMA_CTRL_RESET, DMA_CTRL_RESET);
        seq->npu_maskwrite(get_tile(row, col), offset, 0, DMA_CTRL_RESET);
        writes += 2;
    };
    if (full) {
        for (const reg_write& ch : all_channels) reset(ch.row, ch.col, ch.offset);
    } else {
        for (const chain_start& s : config_of(from).starts) reset(s.row, s.col, s.ctrl_offset);
    }
    // 2. routes: this op's value, or 0 (port off) where only the other op
    //    routes; after a known op only the registers whose value differs
    for (const reg_key& key : sw_regs) {
        const uint32_t v = value_in(cfg.sw, key);
        if (!full && v == value_in(config_of(from).sw, key)) continue;
        write_reg(seq, std::get<1>(key), std::get<0>(key), std::get<2>(key), v);
        writes++;
    }
    for (const mask_write& m : cfg.mux) {
        seq->npu_maskwrite(get_tile(m.row, m.col), m.offset, m.value, m.mask);
        writes++;
    }
    // 3. BDs: those only one op uses stay loaded once written (full switch);
    //    those both ops use are this op's again after every switch
    if (full) {
        for (const op_config* c : {&op_dq, &op_attn})
            for (const reg_block& b : c->bds)
                if (!b.shared) writes += write_bd(seq, b);
    }
    for (const reg_block& b : cfg.bds)
        if (b.shared) writes += write_bd(seq, b);
    // 4. lock values, after the reset (a reset chain may hold a lock count).
    //    Not the op lock: every core is waiting on it right now.
    for (const reg_key& key : lock_regs) {
        if (std::get<1>(key) >= 2 && std::get<2>(key) == OP_LOCK_REG) continue;
        write_reg(seq, std::get<1>(key), std::get<0>(key), std::get<2>(key), value_in(cfg.locks, key));
        writes++;
    }
    // 5. start the op's chains
    for (const chain_start& s : cfg.starts) {
        write_reg(seq, s.row, s.col, s.queue_offset, s.queue_value);
        write_reg(seq, s.row, s.col, s.ctrl_offset, s.ctrl_value);
        writes += 2;
    }
    return writes;
}

/// @brief per-core RTP block for one run of `op`, then let the cores go
/// @param extra (index, value) pairs of the op's own RTP fields
inline void gen_dispatch(npu_sequence* seq, int op, int calls, bool switched, int cols,
                         std::initializer_list<std::pair<int, uint32_t>> extra) {
    for (int r = 0; r < ROWS; r++) {
        for (int c = 0; c < cols; c++) {
            const uint32_t row = r + 2;
            for (const auto& [idx, value] : extra) write_reg(seq, row, c, RTP_ADDR + 4 * idx, value);
            write_reg(seq, row, c, RTP_ADDR + 4 * RTP_OP, op);
            write_reg(seq, row, c, RTP_ADDR + 4 * RTP_CALLS, calls);
            write_reg(seq, row, c, RTP_ADDR + 4 * RTP_SWITCHED, switched ? 1 : 0);
        }
    }
    // after all RTPs: the cores read them as soon as their lock is set
    for (int r = 0; r < ROWS; r++)
        for (int c = 0; c < cols; c++) write_reg(seq, r + 2, c, OP_LOCK_REG, 1);
}

/// @brief one dequant_mm run: y[L][Dout] = x[L][Din] W^T, W q4_k (pairs layout).
///        Buffers: arg 0 = y, 1 = x, 2 = w.  L % 256, Din % 256, Dout % 512.
/// @param configured the op the array is set up for; updated to OP_DQ
inline void gen_dq_run(npu_sequence* seq, int& configured, const uint32_t L, const uint32_t Din, const uint32_t Dout,
                       const size_t weight_offset, const size_t out_offset, const int rtp_act) {
    static constexpr npu_tiles IT[8] = {IT0, IT1, IT2, IT3, IT4, IT5, IT6, IT7};
    static constexpr int m = QXNX_ROW_BLOCK_SIZE;
    static constexpr int k = QXNX_COL_BLOCK_SIZE;
    static constexpr uint32_t desired_m = 64;    // kernel/dq/common.hpp NPU_M_TILE
    static constexpr uint32_t desired_k = 256;   // NPU_K_TILE: one Q4_K block
    static constexpr uint32_t desired_n = 64;
    const uint32_t columns = 8;
    const int K_div_k = Din / desired_k;
    assert(Dout % (m * columns) == 0 && Din % desired_k == 0);
    const int M_div_m = L / (desired_m * 4);
    const int N_div_n = Dout / desired_n / columns;
    assert(L % (desired_m * 4) == 0);
    (void)k;

    seq->clear_cmds();
    const bool switched = configured != OP_DQ;
    if (switched) gen_switch(seq, OP_DQ, configured);
    configured = OP_DQ;
    // every core computes one 128 x 64 tile per round
    gen_dispatch(seq, OP_DQ, M_div_m * N_div_n, switched, COLS,
                 {{RTP_DQ_K_DIV_K, (uint32_t)K_div_k}, {RTP_DQ_ACT, (uint32_t)rtp_act}});

    for (int i = 0; i < M_div_m; i++) {
        for (int j = 0; j < N_div_n; j++) {
            int round = i * N_div_n + j;
            int bd_offset = (round % 2) * 8;
            uint32_t y_offset = i * desired_m * 4 * Dout + j * desired_n * columns;
            uint32_t x_offset = i * desired_m * 4 * Din;
            int w_offset = get_quantization_byte_size((size_t)j * desired_n * Din * columns, flm_q4k) + weight_offset;
            npu_bd_id y_bd_0 = npu_bd_id(0 + bd_offset);
            npu_bd_id y_bd_1 = npu_bd_id(3 + bd_offset);
            npu_bd_id x_bd = npu_bd_id(1 + bd_offset);
            npu_bd_id w_bd_0 = npu_bd_id(2 + bd_offset);
            npu_bd_id w_bd_1 = npu_bd_id(4 + bd_offset);
            for (uint32_t col = 0; col < 4; col++) {
                seq->npu_dma_memcpy_nd(sizeof(char), 2, MM2S, IT[col], w_bd_0, it_channel_1,
                    {0, 0, 0, (uint32_t)(w_offset + get_quantization_byte_size((size_t)col * desired_n * Din, flm_q4k))},
                    {1, 1, 1, (uint32_t)get_quantization_byte_size(desired_n * Din, flm_q4k)},
                    {0, 0, 0, 1}, -1, 0, false, aggressive_cache);
                seq->npu_dma_memcpy_nd(sizeof(char), 2, MM2S, IT[col + 4], w_bd_1, it_channel_1,
                    {0, 0, 0, (uint32_t)(w_offset + get_quantization_byte_size((size_t)col * desired_n * Din, flm_q4k)
                                         + get_quantization_byte_size(4 * desired_n * Din, flm_q4k))},
                    {1, 1, 1, (uint32_t)get_quantization_byte_size(desired_n * Din, flm_q4k)},
                    {0, 0, 0, 1}, -1, 0, false, aggressive_cache);
                seq->npu_dma_memcpy_nd(2, 0, S2MM, IT[col], y_bd_0, it_channel_0,
                    {0, 0, 0, (uint32_t)(y_offset + col * desired_m * Dout + out_offset)},
                    {1, 1, desired_m, desired_n * 4}, {0, 0, Dout, 1}, -1, 0, true);
                seq->npu_dma_memcpy_nd(2, 0, S2MM, IT[col + 4], y_bd_1, it_channel_0,
                    {0, 0, 0, (uint32_t)(y_offset + col * desired_m * Dout + 4 * desired_n + out_offset)},
                    {1, 1, desired_m, desired_n * 4}, {0, 0, Dout, 1}, -1, 0, true);
                seq->npu_dma_memcpy_nd(2, 1, MM2S, IT[2 * col], x_bd, it_channel_0,
                    {0, 0, 0, x_offset + col * desired_m * Din},
                    {1, (uint32_t)K_div_k, desired_m, desired_k}, {0, desired_k, Din, 1}, -1, 0, false);
            }
            if (round > 0) {
                for (int r = 0; r < 4; r++) {
                    seq->npu_dma_wait(IT[r], S2MM, it_channel_0);
                    seq->npu_dma_wait(IT[r + 4], S2MM, it_channel_0);
                }
            }
        }
    }
    for (int r = 0; r < 4; r++) {
        seq->npu_dma_wait(IT[r], S2MM, it_channel_0);
        seq->npu_dma_wait(IT[r + 4], S2MM, it_channel_0);
    }
    seq->cmds2seq();
}

/// @brief one attention run (Hy: dh 128, GQA, KV cache in the decode layout
///        [K col0][K col1][V col0][V col1]). Buffers: arg 0 = o, 1 = q, 2 = kv cache.
/// @param configured the op the array is set up for; updated to OP_ATTN
inline void gen_attn_run(npu_sequence* seq, int& configured, const uint32_t L_begin, const uint32_t L_wanted,
                         const int MAX_L, const int WINDOW_SIZE, const int lc, const int DH, const int Heads,
                         const int KV_Heads, const int Num_of_d_in_KV_cache, const int KV_CACHE_SIZE,
                         bool is_sliding_window = false) {
    npu_tiles IT[2][2] = {{IT0, IT1}, {IT2, IT3}};
    assert(L_wanted % (lc * 8) == 0);
    const int q_per_kv = Heads / KV_Heads;
    const int using_window_size = is_sliding_window ? WINDOW_SIZE : MAX_L;
    const int Q_chunks = L_wanted / (lc * 8);
    const int num_cu = 2;
    assert(q_per_kv % num_cu == 0);

    seq->clear_cmds();
    const bool switched = configured != OP_ATTN;
    if (switched) gen_switch(seq, OP_ATTN, configured);
    configured = OP_ATTN;
    // one attn() call per head round
    gen_dispatch(seq, OP_ATTN, Heads / num_cu, switched, ATTN_COLS,
                 {{RTP_AT_L_BEGIN, L_begin}, {RTP_AT_L_CHUNKS, (uint32_t)Q_chunks},
                  {RTP_AT_WINDOW, (uint32_t)using_window_size}});

    const int data_per_round = lc * 8;
    for (int head = 0; head < Heads / num_cu; head++) {
        for (int round = 0; round < Q_chunks; round++) {
            int Lq_current = L_begin + round * data_per_round;
            int kv_begin = ((Lq_current - using_window_size) > 0) ? (Lq_current - using_window_size) : 0;
            int kv_end = (Lq_current + 2 * data_per_round - 1) / data_per_round * data_per_round;
            int kv_length = kv_end - kv_begin;
            int bd_offset = (round % 2) * 8;
            for (int cu = 0; cu < num_cu; cu++) {
                int head_offset = head * num_cu + cu;
                for (int col = 0; col < 2; col++) {
                    size_t y_offset = head_offset * DH + (round * data_per_round + col * lc * 4) * DH * Heads;
                    seq->npu_dma_memcpy_nd(2, 0, S2MM, IT[cu][col], (npu_bd_id)(bd_offset + 0), it_channel_0,
                        {0, 0, 0, (uint32_t)y_offset}, {1, 1, (uint32_t)4 * lc, (uint32_t)DH},
                        {0, 0, (uint32_t)DH * Heads, 1}, -1, 0, true);
                }
                size_t q_offset = head_offset * DH + round * data_per_round * DH * Heads;
                seq->npu_dma_memcpy_nd(2, 1, MM2S, IT[cu][0], (npu_bd_id)(bd_offset + 1), it_channel_0,
                    {0, 0, 0, (uint32_t)q_offset}, {1, 1, (uint32_t)lc * 4, (uint32_t)DH},
                    {0, 0, (uint32_t)DH * Heads, 1}, -1, 0, false);
                seq->npu_dma_memcpy_nd(2, 1, MM2S, IT[cu][0], (npu_bd_id)(bd_offset + 2), it_channel_1,
                    {0, 0, 0, (uint32_t)(q_offset + (size_t)lc * 4 * DH * Heads)}, {1, 1, (uint32_t)lc * 4, (uint32_t)DH},
                    {0, 0, (uint32_t)DH * Heads, 1}, -1, 0, false);
            }
            int kv_head_offset = head * num_cu / q_per_kv;
            int kv_chunk_offset = kv_head_offset / Num_of_d_in_KV_cache;
            int kv_head_offset_in_chunk = kv_head_offset % Num_of_d_in_KV_cache;
            size_t k_offset = (size_t)kv_chunk_offset * MAX_L * DH * Num_of_d_in_KV_cache
                              + (size_t)kv_head_offset_in_chunk * DH + (size_t)kv_begin * DH * Num_of_d_in_KV_cache;
            seq->npu_dma_memcpy_nd(2, 2, MM2S, IT[1][1], (npu_bd_id)(bd_offset + 3), it_channel_0,
                {0, 0, 0, (uint32_t)k_offset}, {1, (uint32_t)kv_length / 128, (uint32_t)128, (uint32_t)DH},
                {0, (uint32_t)128 * DH * Num_of_d_in_KV_cache, (uint32_t)DH * Num_of_d_in_KV_cache, 1}, -1, 0, false);
            size_t v_offset = k_offset + KV_CACHE_SIZE / 2;
            seq->npu_dma_memcpy_nd(2, 2, MM2S, IT[1][1], (npu_bd_id)(bd_offset + 4), it_channel_1,
                {0, 0, 0, (uint32_t)v_offset}, {1, (uint32_t)kv_length / 128, (uint32_t)128, (uint32_t)DH},
                {0, (uint32_t)128 * DH * Num_of_d_in_KV_cache, (uint32_t)DH * Num_of_d_in_KV_cache, 1}, -1, 0, false);
            if (round > 0) {
                for (int cu = 0; cu < num_cu; cu++)
                    for (int col = 0; col < 2; col++) seq->npu_dma_wait(IT[cu][col], S2MM, it_channel_0);
            }
        }
        for (int cu = 0; cu < num_cu; cu++)
            for (int col = 0; col < 2; col++) seq->npu_dma_wait(IT[cu][col], S2MM, it_channel_0);
    }
    seq->cmds2seq();
}

/// @brief register writes of one switch (for reporting)
inline size_t switch_writes(int to, int from) {
    npu_sequence scratch(device_npu2, false);
    return gen_switch(&scratch, to, from);
}

