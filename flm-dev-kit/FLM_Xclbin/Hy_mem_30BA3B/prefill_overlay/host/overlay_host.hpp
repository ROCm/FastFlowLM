// Host side of the prefill overlay: switch the array between ops, and the
// instruction sequences of the two ops.
//
// A run of an op = [switch, if another op was configured] + per-core RTP block
// + "go" (op lock = 1) + the op's usual shim DMAs. gen_dq_run / gen_attn_run
// copy gen_dequant_mm_512 (dequant_mm_512x512x512/host/seq_gen.hpp) and
// gen_seq_1_4 (../attention_prefill/host/seq_gen.hpp); only their RTP part changed.
