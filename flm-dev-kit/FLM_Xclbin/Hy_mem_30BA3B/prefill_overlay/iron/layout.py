"""Memory layout of the prefill overlay, shared by the IRON design and the core code.

Each core tile has one arena that both ops lay their buffers into (only one op
runs at a time, and neither keeps state in L1 between runs). Offsets reproduce
the addresses the allocator gave each op's standalone design, so the bank
placement stays the same: the arena starts right after the 4 KB stack.

    python3 layout.py > overlay_layout.h      # the same numbers for the core code
"""

