"""Memory layout of the Hy-MT2 prefill overlay, shared by the IRON design and the core code.

Each core tile has one arena both ops lay their buffers into (only one op runs at
a time, and neither keeps state in L1 between runs). The offsets reproduce the
addresses the former ../fused_prefill's allocator gave each buffer, minus the 4 KB stack,
so every buffer stays in the same memory bank. See README.md.

    python3 layout.py > overlay_layout.h      # the same numbers for the core code
"""

STACK = 4096          # bytes; dequant_mm used 4 KB, attention 3 KB

# ---- core tile arena (byte offsets from the arena start = address - STACK) ----
# dequant_mm even core (rows 2, 4): the q4_k blocks (4736 B) arrive here
CT_DQ_E = dict(qw0=0, y1=4736, y_acc=12288, x0=28672, qw1=36864, x1=45056, y0=53248)
# dequant_mm odd core (rows 3, 5): holds the dequantized w tile both cores use
CT_DQ_O = dict(x1=0, y1=8192, w=12288, y_acc=28672, x0=45056, y0=53248)
# attention (every core of columns 0..3)
CT_AT = dict(q=0, s=8192, y=12288, m=20480, in0=28672, o0=32768, in1=45056, o1=49152)
CT_ARENA_BYTES = 53376

# ---- mem tile arena (byte offsets) ---------------------------------------------
MT_DQ = dict(qw0=0, qw1=65536, x0=131072, x1=196608, y0=262144, y1=327680)
MT_AT_EVEN = dict(q0=0, q1=65536, o0=131072, o1=196608)      # q in, o out
MT_AT_ODD = dict(in0=0, in1=65536, o0=131072, o1=196608)     # k / v in, o out
MT_ARENA_BYTES = 360448

# ---- per-core RTP block (int32 indices), right after the arena ------------------
RTP_WORDS = 32
RTP = dict(op=0, calls=1, switched=2,      # dispatcher
           dq_k_div_k=4, dq_act=5, dq_m16=6,   # dequant_mm
           at_l_begin=8, at_l_chunks=9, at_window=10)   # attention
RTP_ADDR = STACK + CT_ARENA_BYTES

OPS = dict(none=0, dq=1, attn=2)
OP_LOCK = 15          # core lock the dispatcher waits on; the host sets it to 1


def elems(byte_offset, elem_bytes=2):
    """byte offset -> element offset in a bf16 arena"""
    assert byte_offset % elem_bytes == 0
    return byte_offset // elem_bytes


def header():
    L = ["// Generated by iron/layout.py. Do not edit.", "#pragma once", ""]
    L.append(f"constexpr int OVERLAY_STACK = {STACK};")
    L.append(f"constexpr int CT_ARENA_BYTES = {CT_ARENA_BYTES};")
    L.append(f"constexpr int RTP_ADDR = {RTP_ADDR};")
    for prefix, d in (("CT_DQ_E", CT_DQ_E), ("CT_DQ_O", CT_DQ_O), ("CT_AT", CT_AT)):
        for k, v in d.items():
            L.append(f"constexpr int {prefix}_{k.upper()} = {v};   // bytes")
    for k, v in RTP.items():
        L.append(f"constexpr int RTP_{k.upper()} = {v};")
    for k, v in OPS.items():
        L.append(f"constexpr int OP_{k.upper()} = {v};")
    L.append(f"constexpr int OP_LOCK = {OP_LOCK};")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    print(header(), end="")
