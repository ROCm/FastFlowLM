    __attribute__((always_inline)) v64bfloat16 getGeluBf16_nonLUT(v64bfloat16 vInput) {
        aie::vector<bfloat16, 64> x = vInput;

        // Constants
        const bfloat16 k0_5 = 0.5f;
        const bfloat16 k1 = 1.0f;
        const bfloat16 sqrt_2_over_pi = 0.79788456f; // ≈ sqrt(2/π)
        const bfloat16 kBeta = 0.044715f;

        auto v05 = aie::broadcast<bfloat16, 64>(k0_5);
        auto v1 = aie::broadcast<bfloat16, 64>(k1);
        auto vs2opi = aie::broadcast<bfloat16, 64>(sqrt_2_over_pi);
        auto vBeta = aie::broadcast<bfloat16, 64>(kBeta);


        // Compute x^3
        aie::vector<bfloat16, 64> x2 = aie::mul(x, x).template to_vector<bfloat16>();  // x^2
        aie::vector<bfloat16, 64> x3 = aie::mul(x, x2).template to_vector<bfloat16>();  // x^3

        // inner = sqrt(2/pi) * (x + 0.044715 * x^3)
        aie::vector<bfloat16, 64> x3_beta = aie::mul(x3, vBeta).template to_vector<bfloat16>(); 
        aie::vector<bfloat16, 64> inner = aie::add(x, x3_beta); 
        auto inner1 = aie::mul(inner, vs2opi);

        // tanh_out = tanh(inner)
        auto tanh_out = aie::tanh<bfloat16>(inner1.to_vector<float>());

        // result = 0.5 * x * (1 + tanh_out)
        aie::vector<bfloat16, 64> one_plus_tanh = aie::add(tanh_out, v1);
        // Multiply by x and 0.5
        aie::vector<bfloat16, 64> mul_v05 = aie::mul(v05, one_plus_tanh).template to_vector<bfloat16>(); ;
        auto result = aie::mul(x, mul_v05);    
        return result.template to_vector<bfloat16>();
    }
