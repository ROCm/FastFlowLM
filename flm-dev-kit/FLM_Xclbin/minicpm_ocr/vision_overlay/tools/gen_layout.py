"""Core tile memory layout of the vision overlay, read from the two standalone designs.

The overlay keeps every buffer of both ops at the address its standalone design gave it
(../vision_mm design VISION_MM_A, ../vision_attn). This script reads those addresses from the
standalone builds, checks them, and writes:

    build/layout.json             for iron/overlay_aie.py (arena size, stack, go lock)
    build/kernel/overlay_layout.h for kernel/fused.cc
    host/overlay_layout.hpp       for the host (dispatcher words, RTP addresses)

    python3 tools/gen_layout.py MM_ADDRESSES ATTN_ADDRESSES
"""
import json
import os
import re
import sys

STACK = 0xC00          # both kernels' Peano stack frames add up to < 1.2 KB; the mm design uses 3 KB
OP_LOCK = 10           # core lock the dispatcher waits on; neither op uses it
OPS = dict(mm=1, attn=2)
DISPATCH_WORDS = 2     # op, calls
ROWS = range(2, 6)
COLS = range(8)
ELEM_BYTES = dict(bf16=2, f32=4, i32=4, i8=1)


def core_buffers(path):
    """{role: (address, bytes)} for one design, the same on all 32 cores (asserted)."""
    text = open(path).read()
    pattern = (r'aie\.buffer\(%tile_(\d+)_(\d+)\) \{address = (\d+) : i32[^}]*sym_name = "([^"]+)"\}'
               r' : memref<([0-9x]+)x(bf16|f32|i32|i8)>')
    per_tile = {}
    for col, row, addr, name, shape, dtype in re.findall(pattern, text):
        col, row = int(col), int(row)
        if row not in ROWS:
            continue
        suffix = f"_{row}_{col}"
        assert name.endswith(suffix), name
        role = name[: -len(suffix)]
        count = 1
        for d in shape.split("x"):
            count *= int(d)
        per_tile.setdefault((col, row), {})[role] = (int(addr), count * ELEM_BYTES[dtype])
    tiles = sorted(per_tile)
    assert len(tiles) == len(ROWS) * len(COLS), f"{path}: {len(tiles)} core tiles"
    first = per_tile[tiles[0]]
    for t in tiles[1:]:
        assert per_tile[t] == first, f"{path}: core {t} differs from core {tiles[0]}"
    return first


def main():
    mm = core_buffers(sys.argv[1])
    attn = core_buffers(sys.argv[2])
    rtp = dict(mm=mm["rtp"][0], attn=attn["L_attn_core"][0])

    base = min(a for a, _ in list(mm.values()) + list(attn.values()))
    end = max(a + n for a, n in list(mm.values()) + list(attn.values()))
    assert base == STACK, f"lowest buffer at 0x{base:X}, expected right after the 0x{STACK:X} stack"
    dispatch = (end + 15) // 16 * 16
    arena_end = (dispatch + 4 * DISPATCH_WORDS + 63) // 64 * 64

    layout = dict(stack=STACK, arena_base=base, arena_bytes=arena_end - base, op_lock=OP_LOCK,
                  dispatch=dispatch, ops=OPS, rtp=rtp, mm=mm, attn=attn)
    os.makedirs("build/kernel", exist_ok=True)
    json.dump(layout, open("build/layout.json", "w"), indent=1)

    k = ["// Generated by tools/gen_layout.py from the standalone builds. Do not edit.", "#pragma once", ""]
    k.append(f"constexpr int CT_ARENA_BASE = 0x{base:04X};")
    for prefix, table in (("CT_MM", mm), ("CT_AT", attn)):
        for role, (addr, _n) in sorted(table.items()):
            k.append(f"constexpr int {prefix}_{role.upper()} = 0x{addr:04X};")
    k.append(f"constexpr int CT_DISPATCH = 0x{dispatch:04X};")
    for name, v in OPS.items():
        k.append(f"constexpr int OP_{name.upper()} = {v};")
    k.append(f"constexpr int OP_LOCK = {OP_LOCK};")
    open("build/kernel/overlay_layout.h", "w").write("\n".join(k) + "\n")

    h = ["// Generated by tools/gen_layout.py from the standalone builds. Do not edit.", "#pragma once",
         "#include <cstdint>", "", "namespace vision_overlay_layout {"]
    h.append(f"constexpr uint32_t DISPATCH_ADDR = 0x{dispatch:04X};   // word 0 op, word 1 calls")
    h.append(f"constexpr uint32_t OP_LOCK = {OP_LOCK};")
    for name, v in OPS.items():
        h.append(f"constexpr int OP_{name.upper()} = {v};")
    h.append(f"constexpr uint32_t MM_RTP_ADDR = {rtp['mm']};      // the standalone VISION_MM_A address")
    h.append(f"constexpr uint32_t ATTN_RTP_ADDR = {rtp['attn']};    // the standalone vision_attn address")
    h.append("}  // namespace vision_overlay_layout")
    open("host/overlay_layout.hpp", "w").write("\n".join(h) + "\n")

    print(f"stack 0x0000-0x{STACK:04X}, arena 0x{base:04X}-0x{arena_end:04X} ({arena_end - base} B), "
          f"dispatcher words at 0x{dispatch:04X}")
    for name, table in (("mm", mm), ("attn", attn)):
        print(f"  {name:4s} " + ", ".join(f"{r} 0x{a:04X}+{n}" for r, (a, n) in sorted(table.items(), key=lambda x: x[1])))


if __name__ == "__main__":
    main()
