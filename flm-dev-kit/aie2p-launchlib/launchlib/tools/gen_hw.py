# gen_hw.py -- write include/launch/hw/hw_gen.hpp from the aie-rt register header.
#
#   gen_hw.py [--params xaie2pgbl_params.h] [--check]
#
# --params defaults to the aie-rt of $MLIR_AIE_DIR (an mlir-aie source tree).
#
# The table is the stream-switch routing registers of each tile kind of AIE2P:
# every STREAM_SWITCH_{MASTER_CONFIG, SLAVE_CONFIG, SLAVE_<port>[_<n>]_SLOT<n>,
# DETERMINISTIC_MERGE} register. A reset or cold kernel writes 0 to all of them
# that its app does not set: no aiecc design resets the routes of another one.
# Left out: parity, event port selection and adaptive clock (not routing).
# --check compares the file with a new output (make test runs it); without the
# header it says so and passes (hw_gen.hpp is checked in).

import argparse
import os
import re
import sys

DEFAULT_PARAMS = os.path.join(os.environ.get("MLIR_AIE_DIR", ""), "third_party/aie-rt/driver/src/global/xaie2pgbl_params.h")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "include", "launch", "hw", "hw_gen.hpp")

# aie-rt module name -> tile kind, and the address window of its switch.
MODULES = [("PL_MODULE", "shim", 0x3F000, 0x3FFFF),
           ("MEM_TILE_MODULE", "mem", 0xB0000, 0xB0FFF),
           ("CORE_MODULE", "core", 0x3F000, 0x3FFFF)]
# Slot registers may have a port number or not (SLAVE_SOUTH_0_SLOT0, SLAVE_TILE_CTRL_SLOT0).
ROUTING = re.compile(r"STREAM_SWITCH_(MASTER_CONFIG|SLAVE_CONFIG|SLAVE_\w+_SLOT\d+$|DETERMINISTIC_MERGE)")


def routing_registers(text, module, lo, hi):
    regs = set()
    for name, value in re.findall(r"^#define XAIE2PGBL_" + module + r"_(STREAM_SWITCH_\w+)\s+(0x[0-9A-Fa-f]+)", text, re.M):
        if name.endswith(("_LSB", "_MASK", "_WIDTH", "_DEFVAL")) or not ROUTING.match(name):
            continue
        v = int(value, 16)
        if lo <= v <= hi:  # a register address, not a bit field value
            regs.add(v)
    return sorted(regs)


def render(params):
    text = open(params).read()
    out = ["//===- hw_gen.hpp - GENERATED by tools/gen_hw.py, do not edit -*- C++ -*-===//",
           "//",
           "// This file is licensed under the Apache License v2.0 with LLVM Exceptions.",
           "// See https://llvm.org/LICENSE.txt for license information.",
           "// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception",
           "//",
           "// Copyright (C) 2026, Advanced Micro Devices, Inc.",
           "//",
           "//===----------------------------------------------------------------------===//",
           "//",
           f"// Source: aie-rt {os.path.basename(params)} (XAIE2PGBL_*_STREAM_SWITCH_*).",
           "// The stream-switch routing registers of each AIE2P tile kind, tile offsets.",
           "//",
           "//===----------------------------------------------------------------------===//",
           "",
           "#pragma once",
           "",
           "#include <array>",
           "#include <cstdint>",
           "",
           "namespace launch::hw {",
           ""]
    for module, kind, lo, hi in MODULES:
        regs = routing_registers(text, module, lo, hi)
        if not regs:
            sys.exit(f"{params}: no {module} stream switch registers")
        out.append(f"/// {len(regs)} registers ({module}).")
        out.append(f"inline constexpr std::array<uint32_t, {len(regs)}> kSwitchRegs_{kind} = {{")
        for i in range(0, len(regs), 8):
            out.append("    " + ", ".join(f"{r:#07x}" for r in regs[i:i + 8]) + ",")
        out.append("};")
        out.append("")
    out.append("} // namespace launch::hw")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--params", default=DEFAULT_PARAMS)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if not os.path.exists(a.params):
        if a.check:
            print(f"hw_gen.hpp not checked: no {a.params} (set MLIR_AIE_DIR or --params)")
            return
        sys.exit(f"no {a.params}: set MLIR_AIE_DIR or --params")
    text = render(a.params)
    if a.check:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            sys.exit("hw_gen.hpp is not current: run tools/gen_hw.py")
        print("hw_gen.hpp is current")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
